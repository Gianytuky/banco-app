-- BASE DE DATOS: BDBANCO  (version 2)
-- PROYECTO: SISTEMA DE GESTION BANCARIA
-- MOTOR: MySQL 8 / MariaDB 10.4+ (XAMPP)
-- Cambios respecto a la v1:
--   + tabla usuario  (login Spring Security, rol unico ADMIN)
--   + tabla titular  (cuentas con varios titulares / mancomunadas)
--   + tipocuenta.moneda y tipocuenta.mancomunada
--   + cuenta.intentos_fallidos (bloqueo por clave incorrecta)
--   + movimiento.saldo_ant, saldo_post, ref_transf
--   + el movimiento de apertura ahora es tipo 'D' (deposito)
-- Nombres de tablas en minuscula (compatible con Windows y Linux).
-- El usuario admin y las claves de las cuentas se crean al iniciar
-- la aplicacion Spring Boot (DataInitializer) con BCrypt.
-- =====================================================

DROP DATABASE IF EXISTS bdbanco;

CREATE DATABASE bdbanco
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE bdbanco;

-- 1. USUARIOS DEL SISTEMA (personal del banco)
CREATE TABLE usuario (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'ADMIN',
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
);

-- 2. CLIENTES
CREATE TABLE clientes (
    cli_cod CHAR(5) NOT NULL PRIMARY KEY,
    cli_dni CHAR(8) NOT NULL UNIQUE,
    cli_nom VARCHAR(100) NOT NULL,
    cli_tel VARCHAR(15),
    cli_ruc CHAR(11),
    cli_email VARCHAR(120) NOT NULL,
    cli_dir VARCHAR(100),
    fecha_registro DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 3. TIPOS DE CUENTA
CREATE TABLE tipocuenta (
    tip_cta INT NOT NULL PRIMARY KEY,
    tip_nom VARCHAR(30) NOT NULL,
    moneda CHAR(3) NOT NULL,
    mancomunada TINYINT(1) NOT NULL DEFAULT 0
);

