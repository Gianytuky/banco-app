-- 4. CUENTAS
CREATE TABLE cuenta (
    nro_cta CHAR(6) NOT NULL PRIMARY KEY,
    cli_cod CHAR(5) NOT NULL,
    tip_cta INT NOT NULL,
    saldo_cta DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    clave VARCHAR(100),
    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA',
    fecha_apertura DATETIME DEFAULT CURRENT_TIMESTAMP,
    intentos_fallidos INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_cuenta_cliente FOREIGN KEY (cli_cod) REFERENCES clientes(cli_cod),
    CONSTRAINT fk_cuenta_tipo FOREIGN KEY (tip_cta) REFERENCES tipocuenta(tip_cta),
    CONSTRAINT chk_saldo CHECK (saldo_cta >= 0),
    CONSTRAINT chk_estado CHECK (estado IN ('ACTIVA','BLOQUEADA','CERRADA'))
);

-- 5. TITULARES (cli_cod de cuenta = titular principal; aqui van TODOS los titulares)
CREATE TABLE titular (
    nro_cta CHAR(6) NOT NULL,
    cli_cod CHAR(5) NOT NULL,
    PRIMARY KEY (nro_cta, cli_cod),
    CONSTRAINT fk_titular_cuenta FOREIGN KEY (nro_cta) REFERENCES cuenta(nro_cta),
    CONSTRAINT fk_titular_cliente FOREIGN KEY (cli_cod) REFERENCES clientes(cli_cod)
);

-- 6. MOVIMIENTOS  (D = deposito, R = retiro)
CREATE TABLE movimiento (
    nro_cta CHAR(6) NOT NULL,
    nro_mov INT NOT NULL,
    monto_mov DECIMAL(12,2) NOT NULL,
    tipo_mov CHAR(1) NOT NULL,
    descripcion VARCHAR(100),
    fecha_mov DATETIME DEFAULT CURRENT_TIMESTAMP,
    saldo_ant DECIMAL(12,2) NOT NULL,
    saldo_post DECIMAL(12,2) NOT NULL,
    ref_transf VARCHAR(20),
    PRIMARY KEY (nro_cta, nro_mov),
    CONSTRAINT fk_mov_cuenta FOREIGN KEY (nro_cta) REFERENCES cuenta(nro_cta),
    CONSTRAINT chk_monto CHECK (monto_mov > 0),
    CONSTRAINT chk_tipo CHECK (tipo_mov IN ('D','R'))
);

-- 7. INDICES
CREATE INDEX idx_cliente_nombre ON clientes(cli_nom);
CREATE INDEX idx_cuenta_cliente ON cuenta(cli_cod);
CREATE INDEX idx_mov_fecha ON movimiento(fecha_mov);
CREATE INDEX idx_mov_ref ON movimiento(ref_transf);

