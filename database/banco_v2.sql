-- 12. VERIFICACION
SELECT c.nro_cta, GROUP_CONCAT(cl.cli_nom SEPARATOR ' / ') AS titulares, t.tip_nom, t.moneda, c.saldo_cta, c.estado
FROM cuenta c
JOIN titular ti ON ti.nro_cta = c.nro_cta
JOIN clientes cl ON cl.cli_cod = ti.cli_cod
JOIN tipocuenta t ON t.tip_cta = c.tip_cta
GROUP BY c.nro_cta, t.tip_nom, t.moneda, c.saldo_cta, c.estado
ORDER BY c.nro_cta;

-- Los saldos deben coincidir con el ultimo saldo_post de cada cuenta
SELECT c.nro_cta, c.saldo_cta,
       (SELECT m.saldo_post FROM movimiento m WHERE m.nro_cta = c.nro_cta ORDER BY m.nro_mov DESC LIMIT 1) AS ultimo_saldo_post
FROM cuenta c ORDER BY c.nro_cta;
